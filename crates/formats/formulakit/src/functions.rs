/// Application prefixes of OpenFormula functions that ship with the office suite.
const APP_PREFIXES: &[&str] = &["ORG.OPENOFFICE.", "ORG.LIBREOFFICE."];

/// Functions whose result changes without a change of their inputs.
const VOLATILE: &[&str] = &[
    "CELL",
    "INDIRECT",
    "INFO",
    "NOW",
    "OFFSET",
    "RAND",
    "RANDARRAY",
    "RANDBETWEEN",
    "TODAY",
];

/// Storage prefixes removed for display: future functions, worksheet functions, user
/// functions and LET/LAMBDA parameters (Excel), Excel functions inside OpenFormula.
const PREFIXES: &[&str] = &["_xlfn.", "_xlws.", "_xludf.", "_xlpm.", "com.microsoft."];

/// The name without its storage prefixes, and whether one of them was `_xludf.`.
pub(crate) fn strip_prefixes(name: &str) -> (&str, bool) {
    let mut rest = name;
    let mut udf = false;
    'outer: loop {
        for prefix in PREFIXES {
            if let Some(head) = rest.get(..prefix.len())
                && head.eq_ignore_ascii_case(prefix)
                && let Some(tail) = rest.get(prefix.len()..)
            {
                udf |= *prefix == "_xludf.";
                rest = tail;
                continue 'outer;
            }
        }
        return (rest, udf);
    }
}

/// Whether `upper` (a name without prefixes, uppercased) is a built-in function.
pub(crate) fn is_builtin(upper: &str) -> bool {
    EXCEL.binary_search(&upper).is_ok()
        || OPENFORMULA.binary_search(&upper).is_ok()
        || APP_PREFIXES.iter().any(|p| upper.starts_with(p))
}

/// Whether `upper` (a name without prefixes, uppercased) is a volatile function.
pub(crate) fn is_volatile(upper: &str) -> bool {
    VOLATILE.binary_search(&upper).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_and_unique() {
        for list in [EXCEL, OPENFORMULA, VOLATILE] {
            assert!(list.windows(2).all(|w| w[0] < w[1]), "{:?}", list.first());
        }
        assert!(EXCEL.len() > 500);
    }

    #[test]
    fn prefixes_strip_in_any_case_and_order() {
        assert_eq!(strip_prefixes("_xlfn._xlws.SORT"), ("SORT", false));
        assert_eq!(strip_prefixes("_XLFN.LET"), ("LET", false));
        assert_eq!(strip_prefixes("_xludf.Foo"), ("Foo", true));
        assert_eq!(strip_prefixes("COM.MICROSOFT.XLOOKUP"), ("XLOOKUP", false));
        assert_eq!(strip_prefixes("SUM"), ("SUM", false));
        assert!(is_builtin("ORG.OPENOFFICE.WEEKS"));
        assert!(!is_builtin("MYVBAFN"));
    }
}
