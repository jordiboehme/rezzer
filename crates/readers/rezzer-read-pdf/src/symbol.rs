/// The character code `code` of the font `Symbol` stands for, if it stands for one.
pub(crate) fn to_unicode(code: u8) -> Option<char> {
    let i = usize::from(code).checked_sub(0x20)?;
    TABLE.get(i).copied().flatten()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn greek_and_signs() {
        assert_eq!(to_unicode(b'a'), Some('\u{3b1}'));
        assert_eq!(to_unicode(b'W'), Some('\u{3a9}'));
        assert_eq!(to_unicode(b'p'), Some('\u{3c0}'));
        assert_eq!(to_unicode(0xB3), Some('\u{2265}'));
        assert_eq!(to_unicode(0xA0), Some('\u{20ac}'));
        assert_eq!(to_unicode(0xFE), Some('\u{f8fe}'));
        // Digits and most signs stand for themselves.
        assert_eq!(to_unicode(b'7'), Some('7'));
        assert_eq!(to_unicode(b'('), Some('('));
        // No character: below the table, the gap and 0xF0.
        assert_eq!(to_unicode(0x1F), None);
        assert_eq!(to_unicode(0x7F), None);
        assert_eq!(to_unicode(0x9F), None);
        assert_eq!(to_unicode(0xF0), None);
        assert_eq!(to_unicode(0xFF), None);
    }
}
